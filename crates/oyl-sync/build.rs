//! Generates the sp00ky client's schema from Oyl Cloud's schema
//! (`schema/src/schema.surql`), so the app's live reads always match it.
//!
//! sp00ky expands each `-- @crdt` field into tables of its own (the edit log
//! a client writes and watches). Its Rust codegen does not, so the client's
//! form of those tables is taken from what `pnpm generate` (`spky generate`)
//! wrote for the web app, `apps/web/src/schema.gen.ts`, and appended.

use std::path::PathBuf;

/// Where the generated block for `@crdt` fields starts in the web app's schema.
const CRDT_BLOCK: &str = "-- Generated by sp00ky for \\`@crdt\\` fields.";

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let schema = manifest.join("../../schema/src/schema.surql");
    let generated = manifest.join("../../apps/web/src/schema.gen.ts");
    println!("cargo:rerun-if-changed={}", schema.display());
    println!("cargo:rerun-if-changed={}", generated.display());
    let mut surql = std::fs::read_to_string(&schema)
        .unwrap_or_else(|err| panic!("reading {}: {err}", schema.display()));
    let web = std::fs::read_to_string(&generated)
        .unwrap_or_else(|err| panic!("reading {}: {err}", generated.display()));
    surql.push_str(&crdt_tables(&web));
    let code = spooky_core::codegen::generate_rust(&surql, &[])
        .unwrap_or_else(|err| panic!("generating the client schema: {err}"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("cloud_schema.rs");
    std::fs::write(&out, code).unwrap_or_else(|err| panic!("writing {}: {err}", out.display()));
}

/// The client tables of the `@crdt` fields, from the web app's generated
/// schema (a template literal: backticks come escaped), up to the next
/// section. Empty without `@crdt` fields.
fn crdt_tables(web: &str) -> String {
    let Some(start) = web.find(CRDT_BLOCK) else {
        return String::new();
    };
    let rest = &web[start..];
    let end = ["-- Backend Schema", "`;"]
        .iter()
        .filter_map(|marker| rest.find(marker))
        .min()
        .unwrap_or(rest.len());
    let block = rest[..end].replace("\\`", "`").replace("\\\\", "\\");
    format!("\n{block}\n")
}
